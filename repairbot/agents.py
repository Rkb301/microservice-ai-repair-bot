"""LangChain agent factories and agent-facing tool adapters."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Callable

from .config import RepairBotSettings
from .prompts import FIX_AGENT_SYSTEM_PROMPT, PR_AGENT_SYSTEM_PROMPT
from .tools import filesystem, github_ops


class AgentUnavailableError(RuntimeError):
    """Raised when optional LangChain dependencies or provider keys are unavailable."""


@dataclass
class RepoToolContext:
    repo_path: str
    allow_sensitive_edits: bool = False
    allow_deploy_edits: bool = False


def create_fix_agent(settings: RepairBotSettings, context: RepoToolContext) -> Any:
    create_agent = _import_create_agent()
    tools = _build_fix_tools(context)
    return create_agent(
        model=settings.model,
        tools=tools,
        system_prompt=FIX_AGENT_SYSTEM_PROMPT,
    )


def create_pr_agent(settings: RepairBotSettings) -> Any:
    create_agent = _import_create_agent()
    return create_agent(
        model=settings.model,
        tools=[],
        system_prompt=PR_AGENT_SYSTEM_PROMPT,
    )


def invoke_fix_agent(
    *,
    settings: RepairBotSettings,
    context: RepoToolContext,
    task: str,
) -> str:
    agent = create_fix_agent(settings, context)
    result = agent.invoke({"messages": [{"role": "user", "content": task}]})
    return _last_message_text(result)


def build_pr_body(
    *,
    service_name: str,
    diagnosis: str | None,
    fix_plan: str | None,
    changed_files: list[str],
    test_cmd: str | None,
    test_output: str | None,
) -> str:
    files = "\n".join(f"- `{file}`" for file in changed_files) or "- None"
    return f"""## AI-generated repair

This pull request was generated by `microservice-ai-repair-bot` and requires human review before merge.

## Service

`{service_name}`

## Diagnosis

{diagnosis or "No diagnosis was recorded."}

## Fix plan

{fix_plan or "No fix plan was recorded."}

## Files changed

{files}

## Tests

Command: `{test_cmd or "not provided"}`

```
{(test_output or "No test output captured.")[-4000:]}
```

## Manual review checklist

- [ ] Confirm the root cause matches the production logs.
- [ ] Review the patch for unintended behavior changes.
- [ ] Confirm CI passes in GitHub.
- [ ] Confirm no secrets, deployment files, or GitHub workflow files were changed unexpectedly.
- [ ] Merge only after normal repository review requirements are satisfied.
"""


def _import_create_agent() -> Callable[..., Any]:
    try:
        from langchain.agents import create_agent
    except ImportError as exc:
        raise AgentUnavailableError(
            "LangChain is not installed. Install the project dependencies before "
            "running AI repair: python -m pip install -e ."
        ) from exc
    return create_agent


def _tool_decorator() -> Callable[..., Any]:
    try:
        from langchain.tools import tool
    except ImportError as exc:
        raise AgentUnavailableError(
            "LangChain tools are unavailable. Install compatible LangChain packages."
        ) from exc
    return tool


def _build_fix_tools(context: RepoToolContext) -> list[Any]:
    tool = _tool_decorator()
    repo_path = context.repo_path

    @tool
    def read_file(path: str) -> str:
        """Read a UTF-8 text file inside the target repository."""
        return filesystem.read_file(repo_path, path)

    @tool
    def list_files(pattern: str = "**/*") -> list[str]:
        """List files inside the target repository."""
        return filesystem.list_files(repo_path, pattern=pattern)

    @tool
    def search_repo(query: str) -> list[str]:
        """Search repository text files for a string or symbol."""
        return filesystem.search_repo(repo_path, query)

    @tool
    def write_file_safely(path: str, content: str) -> str:
        """Write a file inside the repository after safety checks."""
        return filesystem.write_file_safely(
            repo_path,
            path,
            content,
            allow_sensitive_edits=context.allow_sensitive_edits,
            allow_deploy_edits=context.allow_deploy_edits,
        )

    @tool
    def replace_text_safely(path: str, old: str, new: str) -> str:
        """Replace the first matching text span in a repository file."""
        return filesystem.replace_text_safely(
            repo_path,
            path,
            old,
            new,
            allow_sensitive_edits=context.allow_sensitive_edits,
            allow_deploy_edits=context.allow_deploy_edits,
        )

    return [read_file, list_files, search_repo, write_file_safely, replace_text_safely]


def _last_message_text(result: Any) -> str:
    if isinstance(result, dict):
        messages = result.get("messages")
        if messages:
            last = messages[-1]
            content = getattr(last, "content", None)
            if content is not None:
                return str(content)
            if isinstance(last, dict):
                return str(last.get("content", ""))
        structured = result.get("structured_response")
        if structured is not None:
            return str(structured)
    return str(result)


def open_pull_request_from_state(
    *,
    github_repo: str,
    branch_name: str,
    base_branch: str,
    service_name: str,
    diagnosis: str | None,
    fix_plan: str | None,
    changed_files: list[str],
    test_cmd: str | None,
    test_output: str | None,
    token: str | None,
) -> str:
    title = f"AI repair for {service_name}"
    body = build_pr_body(
        service_name=service_name,
        diagnosis=diagnosis,
        fix_plan=fix_plan,
        changed_files=changed_files,
        test_cmd=test_cmd,
        test_output=test_output,
    )
    return github_ops.create_pull_request(
        github_repo=github_repo,
        title=title,
        body=body,
        head=branch_name,
        base=base_branch,
        token=token,
    )
